from __future__ import annotations

from .schema import SignalDefinition, SignalOutputType, SignalView


def _signal(
    name: str,
    view: SignalView,
    definition: str,
    inputs: tuple[str, ...],
    output_type: SignalOutputType,
    applicability: str,
    missing: str,
    evidence: str,
    attacks: tuple[str, ...],
    explanation: str,
    *,
    value_range: tuple[float, float] | None = None,
    query: bool = False,
    version_chain: bool = False,
) -> SignalDefinition:
    return SignalDefinition(
        signal_name=name,
        view=view,
        definition=definition,
        input_fields=inputs,
        output_type=output_type,
        value_range=value_range,
        applicability=applicability,
        missing_value_semantics=missing,
        evidence_dependency=evidence,
        candidate_dependency=True,
        query_dependency=query,
        version_chain_dependency=version_chain,
        expected_attack_relevance=attacks,
        explanation_role=explanation,
    )


